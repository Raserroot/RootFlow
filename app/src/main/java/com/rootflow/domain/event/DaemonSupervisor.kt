package com.rootflow.domain.event

/**
 * 「一直运行」常驻脚本的**监管端口**（阶段 10）。
 *
 * ## 它做什么
 * 把标了「一直运行」的脚本当**常驻进程**看着：
 * ```
 * 前台服务起来  → 为每个常驻脚本各起一个监管协程
 *   监管协程    → 启动脚本 → 等它结束 → 退避 → 再启动 …（循环）
 * 前台服务停了  → 取消全部监管协程，脚本随之被终止
 * 熔断（安全模式）→ 同样中止（用户 2026-09-20 裁定：常驻脚本也受安全模式约束）
 * ```
 *
 * ## 与熔断的关系（**三条裁定，勿改**）
 * 用户 2026-09-20 对三个冲突点做了裁定：
 *
 * | 冲突点 | 裁定 |
 * |---|---|
 * | 超时 | 常驻脚本**不限时**（用 `Long.MAX_VALUE`；`timeoutSec = 0` 那条路是"回落 60 秒"，不适用） |
 * | 并发名额 | **占用**全局名额（上限仍 4）。超出会被拒绝并记日志，不静默 |
 * | 崩溃 | **退避重试**，连续快速崩 5 次后**只停掉它自己**，**不触发全局熔断** |
 *
 * 第三条是刻意的：现有熔断规则是"同一脚本连续失败 3 次 ⇒ 全局安全模式"，
 * 而常驻脚本"退出即重启"会反复失败 —— 照搬会让一个写错的常驻脚本冻结整个 App。
 * 局部收敛的节奏见 [DaemonRestartPolicy]。
 *
 * ## 为什么是"监管"而不是"加一个事件源"
 * 「一直运行」没有外部事件。它复用触发器的落库形态（`triggers.event_type = always_run`），
 * 但**驱动者是本端口**而不是 `EventBus`：事件源是"外部发生什么"，
 * 这里是"宿主决定一直看着它"，两者的失败模式与生命周期都不同。
 */
interface DaemonSupervisor {
    /**
     * 开始监管全部已启用的「一直运行」脚本。**幂等**：重复调用不得起第二份。
     *
     * 由 `ForegroundServiceController.register()` 调用（与事件源同属一个所有者，
     * 因为常驻脚本也必须"须驻留前台服务"）。
     */
    fun start()

    /**
     * 停止监管并终止全部常驻脚本。**幂等**。
     *
     * 由 `ForegroundServiceController.unregister()` 调用。
     */
    fun stop()

    /**
     * 当前被监管的脚本数（真机判读 + 单测断言用）。
     *
     * **不含**已放弃重启的那些 —— 它们不再被监管，这是如实计数。
     */
    val supervisedCount: Int

    /**
     * 当前被监管的脚本 id 集合（P4 的「为什么没跑」用）。
     *
     * ## 为什么需要它（而不是查 [supervisedCount]）
     * 「为什么没跑」要回答的是**某一个**脚本的状态，而计数只能说明"总共有几个"。
     * 少了这个口，UI 只能靠"数量对不对"猜某个脚本在不在名单里 —— 那正是本仓库
     * 反复禁止的形态：**用一个间接指标去断言一件具体的事**。
     *
     * 与 [givenUpReasons] 的分工：本方法回答"在不在监管名单"，
     * 后者回答"为什么被踢出了名单"。两者都命中时（极短窗口）以 [givenUpReasons] 为准
     * （放弃意味着它不再被监管）。
     */
    fun supervisedIds(): Set<Long>

    /**
     * 已放弃重启的脚本 id 与原因（真机判读 + 测试断言用）。
     *
     * 放弃后**必须留痕**：否则用户看到的是"脚本不跑了"，而日志里什么都没有
     * ——本仓库反复禁止的静默失败形态。
     */
    fun givenUpReasons(): Map<Long, String>
}
